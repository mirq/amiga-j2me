#!/bin/sh
# Assembles hal/amiga/stub/tls68k.s (the 68k helper of the WarpOS TLS code) and
# writes its bytes to hal/amiga/stub/tls68k.h. Run after changing the .s file.
set -e
cd "$(dirname "$0")/.."
T=$(mktemp -d)
/opt/amiga/bin/m68k-amigaos-as -m68020 hal/amiga/stub/tls68k.s -o $T/s.o
/opt/amiga/bin/m68k-amigaos-objcopy -O binary -j .text $T/s.o $T/s.bin
BOOT=$(/opt/amiga/bin/m68k-amigaos-nm $T/s.o | awk '$3=="boot"{print $1}')
python3 - $T/s.bin hal/amiga/stub/tls68k.h $BOOT <<'PY'
import sys
d = open(sys.argv[1], 'rb').read()
assert d[0:2] == bytes.fromhex('2a7c') and d[2:6] == bytes.fromhex('12345678'), 'the first instruction must be movea.l #imm,a5'
out = ['/* generated by tools/gen-tls-stub.sh from tls68k.s: do not edit */',
       '#define TLS68K_PATCH_OFFSET 2   /* the address of the shared block goes here */',
       '#define TLS68K_BOOT_OFFSET 0x%s   /* boot(): see tls68k.s */' % sys.argv[3],
       '#define TLS68K_HEAD 8448        /* the block: this much, then the code */',
       'static const unsigned char tls68k_code[%d] = {' % len(d)]
for i in range(0, len(d), 12):
    out.append('    ' + ' '.join('0x%02x,' % b for b in d[i:i+12]))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('tls68k.h: %d bytes' % len(d))
PY
rm -rf $T
