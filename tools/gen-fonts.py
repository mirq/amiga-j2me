#!/usr/bin/env python3
"""Generate native/gfx/fontdata.c: 1-bit bitmap fonts.

The two smallest sizes come from the X11 misc-fixed fonts 5x8 and 6x10
(public domain), trimmed to proportional widths; the others are rendered
from DejaVu Sans.

Five pixel sizes, each plain and bold; MIDP small / medium / large are three
neighbouring ones, chosen by the screen height (Font.java). Glyph rows are
16-bit words, MSB = leftmost pixel. Covers ASCII, Latin-1, Latin Extended-A
(Central European) and Cyrillic, plus a few symbols.
Usage: tools/gen-fonts.py [out.c]   (needs Pillow, the DejaVu TTFs and xfonts-base)
"""
import gzip, struct, sys
from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans%s.ttf"
SIZES = [("s7", 7), ("s8", 8), ("s9", 9), ("s11", 11), ("s14", 14)]   # pixel sizes passed to FreeType
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x400, 0x45F), (0x490, 0x491),
          (0x2013, 0x2014), (0x2018, 0x201E), (0x2022, 0x2022), (0x2026, 0x2026),
          (0x20AC, 0x20AC), (0x2116, 0x2116), (0x2122, 0x2122)]
CODES = [c for a, b in RANGES for c in range(a, b + 1)]

def render(font, ascent, height, ch):
    w = max(1, min(16, int(font.getlength(ch) + 0.5)))
    img = Image.new("L", (16, height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    px = img.load()
    rows = []
    for y in range(height):
        v = 0
        for x in range(16):
            if px[x, y] >= 110:
                v |= 0x8000 >> x
        rows.append(v)
    return w, rows

# ---- the two smallest sizes: X11 misc-fixed bitmap fonts (public domain), made proportional ----

def read_pcf(path):
    """Returns (cell_width, ascent, descent, {codepoint: [row bits, MSB = left]})."""
    d = gzip.open(path, "rb").read()
    assert d[:4] == b"\x01fcp"
    n = struct.unpack_from("<i", d, 4)[0]
    tables = {}
    for i in range(n):
        t, fmt, size, off = struct.unpack_from("<iiii", d, 8 + i * 16)
        tables[t] = off
    def order(fmt): return ">" if fmt & 4 else "<"
    # metrics
    off = tables[4]; fmt = struct.unpack_from("<i", d, off)[0]; o = order(fmt)
    metrics = []
    if fmt & 0x100:
        cnt = struct.unpack_from(o + "h", d, off + 4)[0]
        for i in range(cnt):
            lsb, rsb, w, asc, desc = [b - 0x80 for b in d[off + 6 + i * 5: off + 11 + i * 5]]
            metrics.append((lsb, rsb, w, asc, desc))
    else:
        cnt = struct.unpack_from(o + "i", d, off + 4)[0]
        for i in range(cnt):
            lsb, rsb, w, asc, desc, _ = struct.unpack_from(o + "hhhhhH", d, off + 8 + i * 12)
            metrics.append((lsb, rsb, w, asc, desc))
    # bitmaps
    off = tables[8]; fmt = struct.unpack_from("<i", d, off)[0]; o = order(fmt)
    cnt = struct.unpack_from(o + "i", d, off + 4)[0]
    offs = struct.unpack_from(o + "%di" % cnt, d, off + 8)
    data = off + 8 + cnt * 4 + 16
    pad = 1 << (fmt & 3); msbit = bool(fmt & 8)
    # encodings
    off = tables[32]; fmt = struct.unpack_from("<i", d, off)[0]; o = order(fmt)
    c2min, c2max, b1min, b1max, default = struct.unpack_from(o + "hhhhh", d, off + 4)
    cols = c2max - c2min + 1
    idx = struct.unpack_from(o + "%dH" % (cols * (b1max - b1min + 1)), d, off + 14)
    asc = max(m[3] for m in metrics); desc = max(m[4] for m in metrics); cell = max(m[2] for m in metrics)
    glyphs = {}
    for b1 in range(b1min, b1max + 1):
        for c2 in range(c2min, c2max + 1):
            g = idx[(b1 - b1min) * cols + c2 - c2min]
            if g == 0xFFFF: continue
            lsb, rsb, w, ga, gd = metrics[g]
            width = rsb - lsb; stride = ((width + 7) // 8 + pad - 1) // pad * pad
            rows = [0] * (asc + desc)
            for r in range(ga + gd):
                bits = 0
                for x in range(width):
                    byte = d[data + offs[g] + r * stride + x // 8]
                    on = byte & (0x80 >> (x % 8)) if msbit else byte & (1 << (x % 8))
                    if on and 0 <= lsb + x < 16: bits |= 0x8000 >> (lsb + x)
                rows[asc - ga + r] = bits
            glyphs[(b1 << 8) | c2] = rows
    return cell, asc, desc, glyphs

def bitmap_glyph(rows, cell, bold):
    """Trims a fixed-cell glyph to its ink (+1 column of spacing); bold = smeared one pixel right."""
    if bold: rows = [r | (r >> 1) for r in rows]
    ink = 0
    for r in rows: ink |= r
    if ink == 0: return max(2, cell - 2), rows
    left = 0
    while not (ink & (0x8000 >> left)): left += 1
    right = 15
    while not (ink & (0x8000 >> right)): right -= 1
    return right - left + 2, [(r << left) & 0xFFFF for r in rows]

PCF = {"s7": "/usr/share/fonts/X11/misc/5x8.pcf.gz", "s8": "/usr/share/fonts/X11/misc/6x10.pcf.gz"}

out = []
out.append("/* Generated by tools/gen-fonts.py from X11 misc-fixed (5x8, 6x10) and DejaVu Sans. Do not edit. */")
out.append('#include "gfx.h"\n')
fonts = []
for sname, px in SIZES:
    for style, suffix in (("plain", ""), ("bold", "-Bold")):
        name = "font_%s_%s" % (sname, style)
        glyph_rows, table = [], []
        if sname in PCF:
            cell, ascent, descent, glyphs = read_pcf(PCF[sname])
            height = ascent + descent
            for c in CODES:
                rows = glyphs.get(c) or glyphs.get(ord("?"))
                w, rows = bitmap_glyph(rows, cell, style == "bold")
                table.append((c, w, len(glyph_rows)))
                glyph_rows.extend(rows)
        else:
            font = ImageFont.truetype(TTF % suffix, px)
            ascent, descent = font.getmetrics()
            height = ascent + descent
            for c in CODES:
                w, rows = render(font, ascent, height, chr(c))
                table.append((c, w, len(glyph_rows)))
                glyph_rows.extend(rows)
        out.append("static const uint16_t %s_rows[] = {" % name)
        for i in range(0, len(glyph_rows), 12):
            out.append("  " + ",".join("0x%04x" % v for v in glyph_rows[i:i + 12]) + ",")
        out.append("};")
        out.append("static const GfxGlyph %s_glyphs[] = {" % name)
        for i in range(0, len(table), 6):
            out.append("  " + " ".join("{0x%04x,%d,%d}," % t for t in table[i:i + 6]))
        out.append("};")
        fonts.append((name, height, ascent, len(table)))
out.append("\nconst GfxFont gfx_fonts[GFX_FONT_COUNT] = {")
for name, height, ascent, n in fonts:
    out.append("  { %d, %d, %d, %s_glyphs, %s_rows }," % (height, ascent, n, name, name))
out.append("};")
path = sys.argv[1] if len(sys.argv) > 1 else "native/gfx/fontdata.c"
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path, [(f[0], f[1]) for f in fonts])
