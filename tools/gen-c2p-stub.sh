#!/bin/sh
# Assembles Kalms' c2p_rect (hal/amiga/c2p/c2p_rect.s) as plain position-
# independent 68k code and writes its bytes to hal/amiga/c2p/c2p68k.h, for the
# WarpOS build, which runs it through Run68K (amiga_video.c). The 68k build
# links c2p_glue.s instead. Run after changing c2p_rect.s.
set -e
cd "$(dirname "$0")/.."
T=$(mktemp -d)
/opt/amiga/bin/vasmm68k_mot -quiet -Fbin -m68040 -no-opt -o $T/c.bin hal/amiga/c2p/c2p_rect.s
/opt/amiga/bin/vasmm68k_mot -quiet -Fhunk -m68040 -no-opt -o $T/c.o hal/amiga/c2p/c2p_rect.s
if /opt/amiga/bin/m68k-amigaos-objdump -r $T/c.o | grep -q RELOC; then echo "c2p_rect.s needs relocation: cannot be copied as bytes"; exit 1; fi
python3 - $T/c.bin hal/amiga/c2p/c2p68k.h <<'PY'
import sys
d = open(sys.argv[1], 'rb').read()
assert d[0:2] == bytes.fromhex('48e7'), 'c2p_rect must start the file (movem.l)'
out = ['/* generated by tools/gen-c2p-stub.sh from c2p_rect.s (Mikael Kalms): do not edit */',
       'static const unsigned char c2p68k_code[%d] = {' % len(d)]
for i in range(0, len(d), 12):
    out.append('    ' + ' '.join('0x%02x,' % b for b in d[i:i+12]))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('c2p68k.h: %d bytes' % len(d))
PY
rm -rf $T
